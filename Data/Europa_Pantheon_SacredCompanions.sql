-- Project Europa: the "Sacred Companions" pantheon.
-- Camps over our animal luxuries: +1 Production, +1 Faith.
--
-- In its own file because it is the only pantheon that depends on the luxury resources
-- in Europa_Resources.sql. The eligible resources are an explicit list, tagged
-- CLASS_EUROPA_SACRED_COMPANION. TypeTags has a foreign key to Types, so if a resource
-- below is ever renamed or removed this file fails as a whole (visible in Database.log
-- and in tools/validate.sh) and the pantheon is not offered, instead of being offered
-- and quietly doing nothing. tools/validate.sh also checks that every resource on the
-- list really is improved by a Camp and that no Camp luxury of ours is left off it.
--
-- Not on the list, on purpose: Topaz (Mine) and Discus Fish (Fish Weir).

